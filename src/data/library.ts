function pickContent(bookId: string, category: string, chIdx: number, title: string): string {
  // Map book category to content pool
  const poolMap: Record<string, string[]> = {
    "指数基金": CONTENT_POOL.fund_basic,
    "ETF投资": CONTENT_POOL.etf,
    "债券固收": CONTENT_POOL.bond,
    "人身保险": CONTENT_POOL.life_insurance,
    "财产保险": CONTENT_POOL.general_insurance,
    "价值投资": CONTENT_POOL.value_investing,
    "行为金融": CONTENT_POOL.behavioral,
    "理财心理": CONTENT_POOL.wealth_mindset,
    "经济原理": CONTENT_POOL.economics,
    "财富思维": CONTENT_POOL.wealth_mindset,
  };
  const pool = poolMap[category] || CONTENT_POOL.fund_basic;
  // Hash bookId + chIdx to get a deterministic but different index
  const hash = bookId.split("").reduce((a, c) => a + c.charCodeAt(0), 0) + chIdx;
  const idx = hash % pool.length;
  return `# ${title}\n\n${pool[idx]}`;
}

function mkChapters(bookId: string, category: string, titles: string[]): BookChapter[] {
  return titles.map((title, i) => ({
    slug: `ch${i + 1}`,
    title: `第${["一二三四五六七八九十"][i]}章 ${title}`,
    content: pickContent(bookId, category, i, title),
  }));
}

